def card(icon, title, text, i, compact=False):
    mod = ' approach-card--compact' if compact else ''
    body = f'\n          <p class="approach-card__text">{nb(text)}</p>' if text else ''
    return (f'        <article class="approach-card{mod}">\n'
            f'          <span class="approach-card__icon"><img src="img/icons/approach/{icon}.svg" width="36" height="36" alt="" loading="lazy" decoding="async"></span>\n'
            f'          <h3 class="approach-card__title">{nb(title)}</h3>{body}\n'
            f'        </article>')


