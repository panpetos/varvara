def nb(t):
    """Неразрывные пробелы после коротких слов и перед тире — как во всей вёрстке."""
    t = re.sub(r'(?<![\w-])([А-Яа-яЁёA-Za-z]{1,2}|\d+)\s+(?=\S)', r'\1&nbsp;', t)
    return t.replace(' — ', '&nbsp;— ')


